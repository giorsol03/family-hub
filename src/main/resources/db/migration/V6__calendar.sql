-- Calendar events. Times are local wall-clock times in the household timezone (Europe/Nicosia).
-- All-day events store start/end at 00:00; end_at is the (inclusive) last day.

CREATE TABLE calendar_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(150)  NOT NULL,
    description VARCHAR(2000),
    location    VARCHAR(200),
    type        VARCHAR(15)   NOT NULL,
    all_day     BOOLEAN       NOT NULL DEFAULT FALSE,
    start_at    TIMESTAMP     NOT NULL,
    end_at      TIMESTAMP     NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by  BIGINT REFERENCES member (id)
);

CREATE INDEX ix_calendar_event_range ON calendar_event (start_at, end_at);

CREATE TABLE calendar_event_attendee (
    event_id  BIGINT NOT NULL REFERENCES calendar_event (id) ON DELETE CASCADE,
    member_id BIGINT NOT NULL REFERENCES member (id),
    PRIMARY KEY (event_id, member_id)
);
