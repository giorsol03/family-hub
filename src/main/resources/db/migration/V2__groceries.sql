-- Grocery defaults (reusable templates) and the shopping list itself.
-- Enums are stored as VARCHAR names (see GroceryCategory, QuantityUnit, Merchant, GrocerySource).

CREATE TABLE grocery_default (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(100)   NOT NULL,
    category           VARCHAR(20)    NOT NULL,
    default_quantity   NUMERIC(10, 3) NOT NULL,
    unit               VARCHAR(10)    NOT NULL,
    preferred_merchant VARCHAR(20),
    active             BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by         BIGINT REFERENCES member (id)
);

CREATE TABLE grocery_item (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100)   NOT NULL,
    category   VARCHAR(20)    NOT NULL,
    quantity   NUMERIC(10, 3) NOT NULL,
    unit       VARCHAR(10)    NOT NULL,
    merchant   VARCHAR(20),
    notes      VARCHAR(500),
    bought     BOOLEAN        NOT NULL DEFAULT FALSE,
    bought_at  TIMESTAMP WITH TIME ZONE,
    source     VARCHAR(10)    NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by BIGINT REFERENCES member (id)
);

CREATE INDEX ix_grocery_item_bought_name ON grocery_item (bought, name);

