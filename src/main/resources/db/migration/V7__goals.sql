-- Daily goals (habit tracker): a goal belongs to one member; one check row per goal per day.

CREATE TABLE goal (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(100) NOT NULL,
    owner_id             BIGINT       NOT NULL REFERENCES member (id),
    active               BOOLEAN      NOT NULL DEFAULT TRUE,
    start_date           DATE         NOT NULL,
    target_days_per_week INTEGER,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by           BIGINT REFERENCES member (id)
);

CREATE TABLE goal_check (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goal_id    BIGINT  NOT NULL REFERENCES goal (id) ON DELETE CASCADE,
    check_date DATE    NOT NULL,
    done       BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by BIGINT REFERENCES member (id),
    CONSTRAINT uq_goal_check_goal_date UNIQUE (goal_id, check_date)
);
