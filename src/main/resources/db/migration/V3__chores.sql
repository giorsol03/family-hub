-- Chore templates (reusable defaults, optionally recurring) and chore instances.

CREATE TABLE chore_template (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(100)  NOT NULL,
    description         VARCHAR(1000),
    default_assignee_id BIGINT REFERENCES member (id),
    estimated_minutes   INTEGER,
    recurrence          VARCHAR(15)   NOT NULL,
    recurrence_interval INTEGER,
    active              BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by          BIGINT REFERENCES member (id)
);

CREATE TABLE chore (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          VARCHAR(100)  NOT NULL,
    description    VARCHAR(1000),
    scheduled_date DATE          NOT NULL,
    assignee_id    BIGINT REFERENCES member (id),
    status         VARCHAR(10)   NOT NULL,
    completed_at   TIMESTAMP WITH TIME ZONE,
    completed_by   BIGINT REFERENCES member (id),
    template_id    BIGINT REFERENCES chore_template (id),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by     BIGINT REFERENCES member (id)
);

CREATE INDEX ix_chore_scheduled_date ON chore (scheduled_date);
CREATE INDEX ix_chore_status_scheduled_date ON chore (status, scheduled_date);

