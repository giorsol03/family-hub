-- Recipes with their ingredients and tags.
-- Ingredients and tags are value collections owned by the recipe (no own id/audit columns);
-- "position" keeps the order the user entered them in.

CREATE TABLE recipe (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         VARCHAR(150)   NOT NULL,
    description   VARCHAR(1000),
    servings      INTEGER,
    prep_minutes  INTEGER,
    instructions  VARCHAR(10000),
    image_url     VARCHAR(500),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by    BIGINT REFERENCES member (id)
);

CREATE TABLE recipe_ingredient (
    recipe_id BIGINT         NOT NULL REFERENCES recipe (id) ON DELETE CASCADE,
    position  INTEGER        NOT NULL,
    name      VARCHAR(100)   NOT NULL,
    quantity  NUMERIC(10, 3) NOT NULL,
    unit      VARCHAR(10)    NOT NULL,
    category  VARCHAR(20),
    PRIMARY KEY (recipe_id, position)
);

CREATE TABLE recipe_tag (
    recipe_id BIGINT      NOT NULL REFERENCES recipe (id) ON DELETE CASCADE,
    position  INTEGER     NOT NULL,
    tag       VARCHAR(40) NOT NULL,
    PRIMARY KEY (recipe_id, position)
);

CREATE INDEX ix_recipe_tag_tag ON recipe_tag (tag);
