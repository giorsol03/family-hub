-- Weekly meal plan: a recipe planned for a day and meal slot. Several recipes per slot are allowed
-- (e.g. a main and a salad for dinner). "Planned by" is created_by.

CREATE TABLE meal_plan_entry (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_date  DATE        NOT NULL,
    slot       VARCHAR(10) NOT NULL,
    recipe_id  BIGINT      NOT NULL REFERENCES recipe (id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by BIGINT REFERENCES member (id)
);

CREATE INDEX ix_meal_plan_entry_plan_date ON meal_plan_entry (plan_date);
CREATE INDEX ix_meal_plan_entry_recipe ON meal_plan_entry (recipe_id);
